// Package pdfstamp menyematkan stempel watermark identitas pengunduh
// (US-11-BE) ke setiap halaman PDF secara in-memory memakai pdfcpu.
//
// Berkas sumber tidak pernah ditulis balik: input dibaca dari io.ReadSeeker,
// hasil ditulis ke io.Writer terpisah, sehingga object asli di MinIO tetap bersih.
package pdfstamp

import (
	"context"
	"fmt"
	"io"
	"strings"
	"time"

	"github.com/pdfcpu/pdfcpu/pkg/api"
	"github.com/pdfcpu/pdfcpu/pkg/pdfcpu/model"
	"github.com/pdfcpu/pdfcpu/pkg/pdfcpu/types"
)

// Identity: data dinamis yang dicetak pada stempel.
type Identity struct {
	BadgeNumber string
	Name        string
	CompanyName string
	DownloadAt  time.Time // sudah dikonversi ke zona waktu tampilan oleh pemanggil
	GeneratedBy string    // URL publik PRIMS
}

// description: tata letak sesuai mockup hal. 3.
//   - pos:tr + off:-12 -12 → pojok kanan atas dengan margin tetap dari tepi
//     kertas (setara x = width-~210, y = height-~90 untuk kotak selebar stempel).
//   - scale:1 abs + points:8 → ukuran font absolut 8pt, tidak ikut skala halaman.
//   - fillc/bo #D9534F + op:0.75 → merah korporat pudar, teks asli tetap terbaca.
//   - bgcol putih wajib ada agar border dirender (syarat pdfcpu); ikut opasitas
//     0.75 sehingga isi dokumen di bawahnya masih samar terlihat.
//
// Nama parameter ditulis lengkap: singkatan seperti "ma" ambigu di pdfcpu.
const description = "fontname:Helvetica, points:8, position:tr, offset:-12 -12, " +
	"scalefactor:1 abs, rotation:0, aligntext:l, fillcolor:#D9534F, " +
	"backgroundcolor:#FFFFFF, border:1 #D9534F, margins:5, opacity:0.75"

// Text menyusun teks stempel multi-baris.
func Text(id Identity) string {
	lines := []string{
		"** DOKUMEN ASLI **",
		"Confidential Document",
		sanitize(id.CompanyName),
		"Downloaded by :",
		"Badge Number : " + sanitize(id.BadgeNumber),
		"Name : " + sanitize(id.Name),
		"Date Time : " + id.DownloadAt.Format("02/01/2006 15:04:05"),
		"Generated By " + sanitize(id.GeneratedBy),
	}
	return strings.Join(lines, "\n")
}

// Stamp membaca PDF dari src, menstempel seluruh halaman, dan menulis hasilnya ke w.
func Stamp(ctx context.Context, src io.ReadSeeker, w io.Writer, id Identity) error {
	// Stateless: konfigurasi bawaan tanpa membaca/membuat ~/.config/pdfcpu
	// di host produksi (server tidak memakai font user pdfcpu).
	conf := model.NewStatelessConfiguration()
	conf.ValidationMode = model.ValidationRelaxed

	wm, err := api.TextWatermark(ctx, Text(id), description, true, false, types.POINTS, conf)
	if err != nil {
		return fmt.Errorf("pdfstamp: konfigurasi stempel: %w", err)
	}

	// selectedPages nil = seluruh halaman.
	if err := api.AddWatermarks(ctx, src, w, nil, wm, conf); err != nil {
		return fmt.Errorf("pdfstamp: stempel PDF: %w", err)
	}
	return nil
}

// sanitize menetralkan sintaks khusus teks stempel pdfcpu: literal "\n"
// dipecah jadi baris baru. Data pengguna tidak boleh bisa mengubah tata letak
// stempel.
func sanitize(s string) string {
	s = strings.ReplaceAll(s, `\`, "/")
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "\r", " ")
	return strings.TrimSpace(s)
}
