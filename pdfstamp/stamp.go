// Package pdfstamp menyematkan stempel watermark identitas pengunduh
// (US-11-BE) ke setiap halaman PDF secara in-memory memakai pdfcpu.
//
// Berkas sumber tidak pernah ditulis balik: input dibaca dari io.ReadSeeker,
// hasil ditulis ke io.Writer terpisah, sehingga object asli di MinIO tetap bersih.
package pdfstamp

import (
	"bytes"
	"context"
	"fmt"
	"io"
	"math"
	"strings"
	"time"
	"unicode"

	"github.com/pdfcpu/pdfcpu/pkg/api"
	"github.com/pdfcpu/pdfcpu/pkg/font"
	"github.com/pdfcpu/pdfcpu/pkg/pdfcpu"
	"github.com/pdfcpu/pdfcpu/pkg/pdfcpu/fault"
	"github.com/pdfcpu/pdfcpu/pkg/pdfcpu/model"
	"github.com/pdfcpu/pdfcpu/pkg/pdfcpu/types"
)

// Identity: data dinamis yang dicetak pada stempel.
type Identity struct {
	BadgeNumber string
	Name        string
	CompanyName string
	DownloadAt  time.Time // sudah dikonversi ke zona waktu tampilan oleh pemanggil
}

const placement = "position:tr, offset:-12 -12, scalefactor:1 abs, rotation:0"

// Text menyusun teks stempel multi-baris.
func Text(id Identity) string {
	lines := []string{
		"** DOKUMEN RESMI **",
		"Confidential Document",
		sanitize(id.CompanyName),
		"Downloaded by :",
		"Badge Number : " + sanitize(id.BadgeNumber),
		"Name : " + sanitize(id.Name),
		"Date Time : " + id.DownloadAt.Format("02/01/2006 15:04:05 MST"),
		"Generated By PRIMS",
	}
	return strings.Join(lines, "\n")
}

// Stamp membaca PDF dari src, menstempel seluruh halaman, dan menulis hasilnya ke w.
func Stamp(ctx context.Context, src io.ReadSeeker, w io.Writer, id Identity) (err error) {
	defer fault.Catch(&err)
	// Stateless: konfigurasi bawaan tanpa membaca/membuat ~/.config/pdfcpu
	// di host produksi (server tidak memakai font user pdfcpu).
	conf := model.NewStatelessConfiguration()
	conf.ValidationMode = model.ValidationRelaxed

	var overlay bytes.Buffer
	if err := writeOverlay(ctx, &overlay, Text(id), conf); err != nil {
		return fmt.Errorf("pdfstamp: buat kotak stempel: %w", err)
	}
	wm, err := api.PDFWatermarkForReadSeeker(ctx, bytes.NewReader(overlay.Bytes()), 1, placement, true, false, types.POINTS)
	if err != nil {
		return fmt.Errorf("pdfstamp: konfigurasi stempel: %w", err)
	}

	conf.Cmd = model.ADDWATERMARKS
	conf.OptimizeDuplicateContentStreams = false
	pdf, err := api.ReadValidateAndOptimize(ctx, src, conf, nil)
	if err != nil {
		return fmt.Errorf("pdfstamp: baca master: %w", err)
	}
	catalog, err := pdf.Catalog()
	if err != nil {
		return err
	}
	originalLayers, hadLayers := catalog["OCProperties"]
	// selectedPages nil = seluruh halaman.
	if err := api.WatermarkContext(ctx, pdf, nil, wm); err != nil {
		return fmt.Errorf("pdfstamp: stempel PDF: %w", err)
	}

	// pdfcpu menautkan form stempel ke layer opsional (bisa layer master
	// yang disembunyikan). Lepas tautan stempel tanpa mengubah layer master.
	if len(wm.FCache) == 0 {
		return fmt.Errorf("pdfstamp: tidak ada halaman yang distempel")
	}
	for _, ref := range wm.FCache {
		form, _, err := pdf.DereferenceStreamDict(*ref)
		if err != nil {
			return err
		}
		form.Delete("OC")
	}
	if hadLayers {
		catalog["OCProperties"] = originalLayers
	} else {
		catalog.Delete("OCProperties")
	}
	return api.WriteContext(ctx, pdf, w)
}

// writeOverlay membuat satu halaman seukuran kotak. Opacity bawaan stamp
// pdfcpu berlaku untuk seluruh form, jadi alpha dipasang hanya pada fill putih.
func writeOverlay(ctx context.Context, w io.Writer, text string, conf *model.Configuration) error {
	const fontName, fontSize, leading, padding = "Helvetica", 8, 10, 5
	const red = "0.850980 0.325490 0.309804" // #D9534F dalam DeviceRGB

	lines := strings.Split(text, "\n")
	var width float64
	for i, line := range lines {
		lines[i] = model.DecodeUTF8ToByte(line) // Helvetica memakai WinAnsi.
		lineWidth, err := font.TextWidth(ctx, lines[i], fontName, fontSize)
		if err != nil {
			return err
		}
		width = max(width, lineWidth)
	}
	width = math.Ceil(width) + 2*padding
	height := float64(len(lines)*leading + 2*padding)

	var content bytes.Buffer
	fmt.Fprintf(&content, "q /BgAlpha gs 1 g 0 0 %.0f %.0f re f Q\n", width, height)
	fmt.Fprintf(&content, "q %s RG 1 w 0.5 0.5 %.0f %.0f re S Q\n", red, width-1, height-1)
	fmt.Fprintf(&content, "BT /F1 %d Tf %d TL %s rg %d %.0f Td\n", fontSize, leading, red, padding, height-padding-fontSize)
	for _, line := range lines {
		// Hex literal menjaga nama/badge tetap sebagai data, bukan operator PDF.
		fmt.Fprintf(&content, "%s Tj T*\n", types.NewHexLiteral([]byte(line)))
	}
	content.WriteString("ET\n")

	pdf, err := pdfcpu.CreateContextWithXRefTable(conf, &types.Dim{Width: width, Height: height})
	if err != nil {
		return err
	}
	parent, err := pdf.Pages()
	if err != nil {
		return err
	}
	root, err := pdf.DereferenceDict(*parent)
	if err != nil {
		return err
	}
	stream, err := pdf.StreamDictIndRef(content.Bytes())
	if err != nil {
		return err
	}
	page, err := pdf.IndRefForNewObject(types.Dict{
		"Type": types.Name("Page"), "Parent": *parent, "Contents": *stream,
		"Resources": types.Dict{
			"Font": types.Dict{"F1": types.Dict{
				"Type": types.Name("Font"), "Subtype": types.Name("Type1"),
				"BaseFont": types.Name(fontName), "Encoding": types.Name("WinAnsiEncoding"),
			}},
			"ExtGState": types.Dict{"BgAlpha": types.Dict{
				"Type": types.Name("ExtGState"), "ca": types.Float(0.75),
			}},
		},
	})
	if err != nil {
		return err
	}
	root["Kids"], root["Count"] = types.Array{*page}, types.Integer(1)
	pdf.PageCount = 1
	return api.WriteContext(ctx, pdf, w)
}

func sanitize(s string) string {
	return strings.TrimSpace(strings.Map(func(r rune) rune {
		if unicode.IsControl(r) || r == '\u2028' || r == '\u2029' {
			return ' '
		}
		return r
	}, s))
}
