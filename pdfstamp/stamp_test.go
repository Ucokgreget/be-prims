// samplePDF membangun PDF valid n halaman A4 berisi teks, lengkap dengan xref.
func samplePDF(t *testing.T, pages int) []byte {
	t.Helper()

	var objs []string
	kids := make([]string, pages)
	// 1: catalog, 2: pages, 3: font, lalu (page, content) per halaman.
	for i := 0; i < pages; i++ {
		kids[i] = fmt.Sprintf("%d 0 R", 4+i*2)
	}
	objs = append(objs,
		"<< /Type /Catalog /Pages 2 0 R >>",
		fmt.Sprintf("<< /Type /Pages /Kids [%s] /Count %d >>", strings.Join(kids, " "), pages),
		"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
	)
	for i := 0; i < pages; i++ {
		// Sudut gelap agar transparansi stempel bisa dilihat pada hasil render.
		content := fmt.Sprintf("q 0 g 380 725 215 117 re f Q BT /F1 24 Tf 72 720 Td (Isi halaman %d) Tj ET", i+1)
		objs = append(objs,
			fmt.Sprintf("<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "+
				"/Resources << /Font << /F1 3 0 R >> >> /Contents %d 0 R >>", 5+i*2),
			fmt.Sprintf("<< /Length %d >>\nstream\n%s\nendstream", len(content), content),
		)
	}

	var b bytes.Buffer
	b.WriteString("%PDF-1.7\n")
	offsets := make([]int, len(objs))
	for i, o := range objs {
		offsets[i] = b.Len()
		fmt.Fprintf(&b, "%d 0 obj\n%s\nendobj\n", i+1, o)
	}
	xref := b.Len()
	fmt.Fprintf(&b, "xref\n0 %d\n0000000000 65535 f \n", len(objs)+1)
	for _, off := range offsets {
		fmt.Fprintf(&b, "%010d 00000 n \n", off)
	}
	fmt.Fprintf(&b, "trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n", len(objs)+1, xref)
	return b.Bytes()
}

func testIdentity() Identity {
	return Identity{
		BadgeNumber: "K-12345",
		Name:        "Budi Santoso",
		CompanyName: "PT Pupuk Sriwidjaja Palembang",
		DownloadAt:  time.Date(2026, 11, 13, 9, 5, 7, 0, time.FixedZone("WIB", 7*3600)),
	}
}

func TestTextFormat(t *testing.T) {
	got := Text(testIdentity())
	want := strings.Join([]string{
		"** DOKUMEN RESMI **",
		"Confidential Document",
		"PT Pupuk Sriwidjaja Palembang",
		"Downloaded by :",
		"Badge Number : K-12345",
		"Name : Budi Santoso",
		"Date Time : 13/11/2026 09:05:07 WIB",
		"Generated By PRIMS",
	}, "\n")
	if got != want {
		t.Fatalf("teks stempel:\n%s\nwant:\n%s", got, want)
	}
}

func TestTextSanitizesUserInput(t *testing.T) {
	id := testIdentity()
	id.Name = "Budi (%p)\\n\nSantoso"
	got := Text(id)
	if strings.Count(got, "\n") != 7 || !strings.Contains(got, `Budi (%p)\n Santoso`) {
		t.Fatalf("input user mengubah jumlah baris stempel: %q", got)
	}
}

func TestStampAllPagesKeepsSourceClean(t *testing.T) {
	src := samplePDF(t, 3)
	pristine := bytes.Clone(src)

	bg := context.Background()
	first := testIdentity()
	second := first
	second.Name, second.BadgeNumber = `Zoë (%p)\n`, "K-54321"
	for _, id := range []Identity{first, second} {
		t.Run(id.BadgeNumber, func(t *testing.T) {
			var out bytes.Buffer
			if err := Stamp(bg, bytes.NewReader(src), &out, id); err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(src, pristine) {
				t.Fatal("buffer sumber ikut berubah")
			}
			if dir := os.Getenv("PDFSTAMP_OUT"); dir != "" && id == first {
				if err := os.WriteFile(dir+"/stamped.pdf", out.Bytes(), 0o644); err != nil {
					t.Fatal(err)
				}
			}

			ctx, err := api.ReadValidateAndOptimize(bg, bytes.NewReader(out.Bytes()), model.NewStatelessConfiguration(), nil)
			if err != nil {
				t.Fatal(err)
			}
			if ctx.PageCount != 3 {
				t.Fatalf("jumlah halaman = %d, want 3", ctx.PageCount)
			}
			for p := 1; p <= ctx.PageCount; p++ {
				checkPageStamp(t, ctx, p, Text(id))
			}
		})
	}
}

func checkPageStamp(t *testing.T, pdf *model.Context, page int, text string) {
	t.Helper()
	d, _, attrs, err := pdf.PageDict(context.Background(), page, true)
	if err != nil {
		t.Fatal(err)
	}
	forms, err := pdf.DereferenceDict(attrs.Resources["XObject"])
	if err != nil || len(forms) != 1 {
		t.Fatalf("halaman %d: harus ada tepat satu form stempel, got %v (%v)", page, forms, err)
	}
	for key, ref := range forms {
		content, err := pdf.PageContent(d, page)
		if err != nil || bytes.Count(content, []byte("/"+key+" Do")) != 1 {
			t.Fatalf("halaman %d: form stempel harus digambar sekali (%v)", page, err)
		}
		form, _, err := pdf.DereferenceStreamDict(ref)
		if err != nil || form == nil {
			t.Fatalf("form stempel: %v", err)
		}
		if _, optional := form.Find("OC"); optional {
			t.Fatal("stempel tidak boleh menjadi layer opsional")
		}
		if err := form.Decode(); err != nil {
			t.Fatal(err)
		}
		for _, line := range strings.Split(text, "\n") {
			hex := types.NewHexLiteral([]byte(model.DecodeUTF8ToByte(line)))
			if bytes.Count(form.Content, []byte(hex.String()+" Tj")) != 1 {
				t.Fatalf("halaman %d: baris stempel tidak tepat: %q", page, line)
			}
		}
	}
}

func TestStampRejectsNonPDF(t *testing.T) {
	var out bytes.Buffer
	err := Stamp(context.Background(), bytes.NewReader([]byte("bukan pdf")), &out, testIdentity())
	if err == nil {
		t.Fatal("harus error untuk input bukan PDF")
	}
}
