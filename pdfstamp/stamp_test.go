// samplePDF membangun PDF valid n halaman A4 berisi teks, lengkap dengan xref.
func samplePDF(t *testing.T, pages int) []byte {
	t.Helper()

	var objs []string
	kids := make([]string, pages)
	// 1: catalog, 2: pages, 3: font, lalu (page, content) per halaman.
	for i := 0; i < pages; i++ {
		kids[i] = fmt.Sprintf("%d 0 R", 4+i*2)
	}
	objs = append(objs,
		"<< /Type /Catalog /Pages 2 0 R >>",
		fmt.Sprintf("<< /Type /Pages /Kids [%s] /Count %d >>", strings.Join(kids, " "), pages),
		"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
	)
	for i := 0; i < pages; i++ {
		content := fmt.Sprintf("BT /F1 24 Tf 72 720 Td (Isi halaman %d) Tj ET", i+1)
		objs = append(objs,
			fmt.Sprintf("<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "+
				"/Resources << /Font << /F1 3 0 R >> >> /Contents %d 0 R >>", 5+i*2),
			fmt.Sprintf("<< /Length %d >>\nstream\n%s\nendstream", len(content), content),
		)
	}

	var b bytes.Buffer
	b.WriteString("%PDF-1.7\n")
	offsets := make([]int, len(objs))
	for i, o := range objs {
		offsets[i] = b.Len()
		fmt.Fprintf(&b, "%d 0 obj\n%s\nendobj\n", i+1, o)
	}
	xref := b.Len()
	fmt.Fprintf(&b, "xref\n0 %d\n0000000000 65535 f \n", len(objs)+1)
	for _, off := range offsets {
		fmt.Fprintf(&b, "%010d 00000 n \n", off)
	}
	fmt.Fprintf(&b, "trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n", len(objs)+1, xref)
	return b.Bytes()
}

func testIdentity() Identity {
	return Identity{
		BadgeNumber: "K-12345",
		Name:        "Budi Santoso",
		CompanyName: "PT Pupuk Sriwidjaja Palembang",
		DownloadAt:  time.Date(2026, 11, 13, 9, 5, 7, 0, time.FixedZone("WIB", 7*3600)),
		GeneratedBy: "https://prims.pusri.co.id",
	}
}

func TestTextFormat(t *testing.T) {
	got := Text(testIdentity())
	want := strings.Join([]string{
		"** DOKUMEN ASLI **",
		"Confidential Document",
		"PT Pupuk Sriwidjaja Palembang",
		"Downloaded by :",
		"Badge Number : K-12345",
		"Name : Budi Santoso",
		"Date Time : 13/11/2026 09:05:07",
		"Generated By https://prims.pusri.co.id",
	}, "\n")
	if got != want {
		t.Fatalf("teks stempel:\n%s\nwant:\n%s", got, want)
	}
}

func TestTextSanitizesUserInput(t *testing.T) {
	id := testIdentity()
	id.Name = "Evil\\nName\nInjected"
	got := Text(id)
	if strings.Count(got, "\n") != 7 || strings.Contains(got, `\n`) {
		t.Fatalf("input user mengubah jumlah baris stempel: %q", got)
	}
}

func TestStampAllPagesKeepsSourceClean(t *testing.T) {
	src := samplePDF(t, 3)
	pristine := bytes.Clone(src)

	var out bytes.Buffer
	if err := Stamp(context.Background(), bytes.NewReader(src), &out, testIdentity()); err != nil {
		t.Fatalf("Stamp: %v", err)
	}

	if !bytes.Equal(src, pristine) {
		t.Fatal("buffer sumber ikut berubah")
	}
	if !bytes.HasPrefix(out.Bytes(), []byte("%PDF-")) {
		t.Fatal("output bukan PDF")
	}

	if dir := os.Getenv("PDFSTAMP_OUT"); dir != "" {
		_ = os.WriteFile(dir+"/stamped.pdf", out.Bytes(), 0o644)
	}

	bg := context.Background()
	conf := model.NewStatelessConfiguration()
	n, err := api.PageCount(bg, bytes.NewReader(out.Bytes()), conf)
	if err != nil {
		t.Fatalf("baca output: %v", err)
	}
	if n != 3 {
		t.Fatalf("jumlah halaman = %d, want 3", n)
	}

	ctx, err := api.ReadValidateAndOptimize(bg, bytes.NewReader(out.Bytes()), conf, nil)
	if err != nil {
		t.Fatalf("output tidak valid: %v", err)
	}
	// Setiap halaman wajib membawa stempel: pdfcpu menyematkannya sebagai
	// form XObject yang dirujuk dari resource halaman.
	for p := 1; p <= n; p++ {
		d, _, inh, err := ctx.PageDict(bg, p, true)
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(d.String(), "XObject") && (inh == nil || inh.Resources == nil ||
			!strings.Contains(inh.Resources.String(), "XObject")) {
			t.Fatalf("halaman %d tidak memiliki stempel: %s", p, d)
		}
	}
}

func TestStampRejectsNonPDF(t *testing.T) {
	var out bytes.Buffer
	err := Stamp(context.Background(), bytes.NewReader([]byte("bukan pdf")), &out, testIdentity())
	if err == nil {
		t.Fatal("harus error untuk input bukan PDF")
	}
}
